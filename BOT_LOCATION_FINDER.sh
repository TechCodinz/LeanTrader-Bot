#!/bin/bash
# FIND WHERE BOT IS RUNNING - COMPREHENSIVE SEARCH

echo "================================================================================"
echo "🔍 COMPREHENSIVE BOT SEARCH"
echo "================================================================================"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
