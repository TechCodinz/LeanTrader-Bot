docker ps -a
if docker ps | grep -qi bot; then
    echo "⚠️  FOUND BOT IN DOCKER!"
    echo "Kill with: docker stop \$(docker ps -q)"
fi
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "2. CRON JOBS"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "User crontab:"
crontab -l 2>/dev/null || echo "No user crontab"
echo ""
echo "Root crontab:"
sudo crontab -l 2>/dev/null || echo "No root crontab"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "3. ALL PYTHON PROCESSES (ALL USERS)"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
ps aux | grep python | grep -v grep
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "4. PROCESSES WITH 'BOT' IN NAME"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
ps aux | grep -iE "bot|trade|profit" | grep -v grep
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "5. TMUX SESSIONS"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
tmux ls 2>/dev/null || echo "No tmux sessions"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "6. PM2 PROCESSES"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
pm2 list 2>/dev/null || echo "PM2 not installed"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "7. BOT DIRECTORIES"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "In home:"
ls -la ~ | grep -E "bot|trade|lean|venv"
echo ""
echo "In /opt:"
sudo ls -la /opt 2>/dev/null | grep -E "bot|trade"
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "8. RECENT LOG FILES"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
find ~ -name "*.log" -mmin -30 2>/dev/null | head -10
echo ""

echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "9. LISTENING PORTS"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
sudo netstat -tlnp | grep -i python 2>/dev/null
sudo ss -tlnp | grep -i python 2>/dev/null
echo ""

echo "================================================================================"
echo "🎯 SUMMARY"
echo "================================================================================"
echo ""

# Check if anything found
found=0

if docker ps | grep -q .; then
    echo "⚠️  Docker containers found!"
    found=1
fi

if crontab -l 2>/dev/null | grep -q .; then
    echo "⚠️  Cron jobs found!"
    found=1
fi

if ps aux | grep python | grep -v grep | grep -q .; then
    echo "⚠️  Python processes found!"
    found=1
fi

if tmux ls 2>/dev/null | grep -q .; then
    echo "⚠️  Tmux sessions found!"
    found=1
fi

if [ $found -eq 0 ]; then
    echo "✅ Nothing found! Bot might be stopped!"
    echo ""
    echo "Check Telegram:"
    echo "  • If no messages for 15+ minutes = Bot is stopped ✅"
    echo "  • If still getting messages = Look in Docker/Cron above"
fi

echo ""
echo "================================================================================"
